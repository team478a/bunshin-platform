import 'server-only';

export type InstagramPublishingFailure =
  | 'INVALID_INPUT'
  | 'AUTHENTICATION'
  | 'PERMISSION'
  | 'RATE_LIMIT'
  | 'PROVIDER_ERROR'
  | 'INVALID_RESPONSE'
  | 'TRANSPORT'
  | 'UNKNOWN_RESULT';

export class InstagramPublishingError extends Error {
  constructor(public readonly category: InstagramPublishingFailure) {
    super('Instagram publishing unavailable');
    this.name = 'InstagramPublishingError';
  }
}

export type InstagramContainerStatus =
  'IN_PROGRESS' | 'FINISHED' | 'PUBLISHED' | 'ERROR' | 'EXPIRED';

type Fetch = typeof fetch;
const graphOrigin = 'https://graph.instagram.com';
const numericId = /^[0-9]{1,30}$/;

function invalid(): never {
  throw new InstagramPublishingError('INVALID_INPUT');
}

function id(value: string): string {
  if (typeof value !== 'string' || !numericId.test(value)) invalid();
  return value;
}

function mediaUrl(value: string): string {
  if (typeof value !== 'string' || value.length > 4096) invalid();
  try {
    const url = new URL(value);
    const host = url.hostname.toLowerCase();
    // These are URLs generated by a trusted, owner-checked media storage adapter.
    // NEVER accept media URLs directly from an untrusted public API request.
    if (
      url.protocol !== 'https:' ||
      url.username ||
      url.password ||
      url.hash ||
      (url.port && url.port !== '443') ||
      host === 'localhost' ||
      host.endsWith('.localhost') ||
      host.endsWith('.internal') ||
      host.startsWith('127.') ||
      host.startsWith('10.') ||
      host.startsWith('192.168.') ||
      host.startsWith('169.254.') ||
      host === '[::1]'
    )
      invalid();
    return url.toString();
  } catch {
    return invalid();
  }
}

function responseId(value: unknown): string {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new InstagramPublishingError('INVALID_RESPONSE');
  }
  const result = (value as Record<string, unknown>)['id'];
  if (typeof result !== 'string' || !numericId.test(result)) {
    throw new InstagramPublishingError('INVALID_RESPONSE');
  }
  return result;
}

function apiFailure(status: number, publishing: boolean): InstagramPublishingError {
  if (status === 401) return new InstagramPublishingError('AUTHENTICATION');
  if (status === 403) return new InstagramPublishingError('PERMISSION');
  if (status === 429) return new InstagramPublishingError('RATE_LIMIT');
  if (publishing && status >= 500) return new InstagramPublishingError('UNKNOWN_RESULT');
  if (status >= 500) return new InstagramPublishingError('PROVIDER_ERROR');
  return new InstagramPublishingError('INVALID_INPUT');
}

/**
 * Internal transport only for Instagram API with Instagram Login.
 * This is NOT OAuth, an authorization bypass, a post scheduler, or an API route.
 * The caller must revalidate owner, content revision, media rights, approval,
 * connected professional account, limits and idempotency before using it.
 */
export class InstagramDirectPublishingAdapter {
  private readonly baseUrl: string;

  constructor(
    apiVersion: string,
    private readonly request: Fetch = fetch,
  ) {
    if (!/^v[1-9][0-9]?\.0$/.test(apiVersion)) invalid();
    this.baseUrl = `${graphOrigin}/${apiVersion}`;
  }

  private async send(
    path: string,
    accessToken: string,
    parameters: URLSearchParams,
    method: 'GET' | 'POST',
    publishing: boolean,
    signal?: AbortSignal,
  ): Promise<unknown> {
    if (typeof accessToken !== 'string' || !accessToken || accessToken.length > 8192) invalid();
    const url = `${this.baseUrl}/${path}${method === 'GET' ? `?${parameters.toString()}` : ''}`;
    let response: Response;
    try {
      response = await this.request(url, {
        method,
        headers: {
          Authorization: `Bearer ${accessToken}`,
          ...(method === 'POST' ? { 'Content-Type': 'application/x-www-form-urlencoded' } : {}),
        },
        ...(method === 'POST' ? { body: parameters.toString() } : {}),
        redirect: 'error',
        cache: 'no-store',
        ...(signal ? { signal } : {}),
      });
    } catch {
      // A failed transport after media_publish can mean success with a lost response.
      // Caller must reconcile with Meta rather than issuing an automatic second publish.
      throw new InstagramPublishingError(publishing ? 'UNKNOWN_RESULT' : 'TRANSPORT');
    }
    if (!response.ok) throw apiFailure(response.status, publishing);
    try {
      return (await response.json()) as unknown;
    } catch {
      throw new InstagramPublishingError(publishing ? 'UNKNOWN_RESULT' : 'INVALID_RESPONSE');
    }
  }

  /** Phase 1: single JPEG image. Media must be temporarily accessible to Meta. */
  async createImageContainer(input: {
    igUserId: string;
    imageUrl: string;
    caption: string;
    accessToken: string;
    signal?: AbortSignal;
  }): Promise<{ containerId: string }> {
    const user = id(input.igUserId);
    const url = mediaUrl(input.imageUrl);
    if (typeof input.caption !== 'string' || [...input.caption].length > 2200) invalid();
    const form = new URLSearchParams({ image_url: url, caption: input.caption });
    const result = await this.send(
      `${user}/media`,
      input.accessToken,
      form,
      'POST',
      false,
      input.signal,
    );
    return { containerId: responseId(result) };
  }

  async inspectContainer(input: {
    containerId: string;
    accessToken: string;
    signal?: AbortSignal;
  }): Promise<InstagramContainerStatus> {
    const container = id(input.containerId);
    const result = await this.send(
      container,
      input.accessToken,
      new URLSearchParams({ fields: 'status_code' }),
      'GET',
      false,
      input.signal,
    );
    if (!result || typeof result !== 'object' || Array.isArray(result))
      throw new InstagramPublishingError('INVALID_RESPONSE');
    const status = (result as Record<string, unknown>)['status_code'];
    if (
      status !== 'IN_PROGRESS' &&
      status !== 'FINISHED' &&
      status !== 'PUBLISHED' &&
      status !== 'ERROR' &&
      status !== 'EXPIRED'
    )
      throw new InstagramPublishingError('INVALID_RESPONSE');
    return status;
  }

  /**
   * Requires a persisted user approval before calling. Never auto-retry a
   * media_publish with an unknown outcome or treat a container as a published post.
   */
  async publishFinishedContainer(input: {
    igUserId: string;
    containerId: string;
    accessToken: string;
    signal?: AbortSignal;
  }): Promise<{ externalPostId: string }> {
    const user = id(input.igUserId);
    const container = id(input.containerId);
    const status = await this.inspectContainer({
      containerId: container,
      accessToken: input.accessToken,
      ...(input.signal ? { signal: input.signal } : {}),
    });
    if (status !== 'FINISHED') throw new InstagramPublishingError('INVALID_INPUT');
    const result = await this.send(
      `${user}/media_publish`,
      input.accessToken,
      new URLSearchParams({ creation_id: container }),
      'POST',
      true,
      input.signal,
    );
    return { externalPostId: responseId(result) };
  }
}
