const themeSituations: Record<FortuneTheme, string> = {
  LOVE: '恋愛で気になる距離感や、次に伝えたいことを一つ思い浮かべてみましょう。',
  WORK: '今日の作業や打ち合わせから、気になっている場面を一つ選んでみましょう。',
  RELATIONSHIPS: '家族や友人、身近な人とのやり取りを一つ思い浮かべてみましょう。',
};

export function dailyCardDetails(cardCode: string, theme: FortuneTheme) {
  if (!Object.hasOwn(cardDetails, cardCode)) return undefined;
  const card = cardDetails[cardCode];
  if (!card) return undefined;
  const [imageDetail, question] = card;
  return { imageDetail, question, situation: themeSituations[theme] };
}
